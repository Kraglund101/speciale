"""
Prepare cashew experiment datasets (real vs synthetic).

Splits:
  - 100 train normals (shared by both datasets)
  - 50 canvas normals (backgrounds for synthetic generation)
  - 50 test normals (shared by both datasets)
  - 50 generation anomalies: 3 hard + 47 easy (masks → canvas, CLIP ref → IP-Adapter)
  - 50 test anomalies: 3 hard + 47 easy (different from generation set)

Structure:
  dataset_real/
    normal/              100 train normals
    anomaly/
      imgs/{easy,hard}   50 generation anomaly images (same anomalies used for synthetic)
      masks/{easy,hard}  50 GT masks
    test/
      normal/            50 test normals
      anomaly/{easy,hard} 50 test anomaly images
      masks/{easy,hard}  50 test GT masks

  dataset_synthetic/
    normal/              100 train normals (same as real)
    source/
      canvas_normals/
        imgs/            50 canvas normals
        masks/           50 BiRefNet foreground masks (run birefnet_canvas.py after)
      reference_anomalies/
        {easy,hard}/
          imgs/          50 anomaly images (CLIP reference)
          masks/         50 anomaly masks (for placement)
    anomaly/
      imgs/{easy,hard}   EMPTY (to be generated by diffusion)
      masks/{easy,hard}  50 placed masks (run viz_mask_placement.py after)
    test/
      normal/            50 test normals (same as real)
      anomaly/{easy,hard} 50 test anomaly images (same as real)
      masks/{easy,hard}  50 test GT masks (same as real)

All selections saved in splits.json for reproducibility.
Files are COPIED (not symlinked) so the experiment is self-contained.
"""

import json
import random
import shutil
from pathlib import Path

SEED = 42
random.seed(SEED)

# ── Paths ─────────────────────────────────────────────────────────────────
CASHEW = Path(
    r"C:\Users\frede\desktop\kandidat\speciale\anomverse_extension"
    r"\datasets\validation\VisA\datasets\easy_test\cashew"
)
NORMAL_DIR = CASHEW / "Data" / "Images" / "Normal"
ANOMALY_DIR = CASHEW / "Data" / "Images" / "Anomaly"
MASK_DIR = CASHEW / "Data" / "Masks" / "Anomaly"
EASY_DIR = ANOMALY_DIR / "easy_imgs"
HARD_DIR = ANOMALY_DIR / "hard_imgs"

EXPERIMENT = CASHEW / "experiment"

# ── Collect source files ──────────────────────────────────────────────────
all_normals = sorted(NORMAL_DIR.glob("*.JPG"))
easy_anomalies = sorted(EASY_DIR.glob("*.JPG"))
hard_anomalies = sorted(HARD_DIR.glob("*.JPG"))

print(f"Normals:        {len(all_normals)}")
print(f"Easy anomalies: {len(easy_anomalies)}")
print(f"Hard anomalies: {len(hard_anomalies)}  ({[f.stem for f in hard_anomalies]})")

# ── Select splits ─────────────────────────────────────────────────────────
# Normals: 100 train + 50 canvas + 50 test
shuffled_normals = list(all_normals)
random.shuffle(shuffled_normals)
train_normals = shuffled_normals[:100]
canvas_normals = shuffled_normals[100:150]
test_normals = shuffled_normals[150:200]

# Hard anomalies: 3 for generation, 3 for test
random.shuffle(hard_anomalies)
gen_hard = hard_anomalies[:3]
test_hard = hard_anomalies[3:]

# Easy anomalies: 47 for generation, 47 for test
random.shuffle(easy_anomalies)
gen_easy = easy_anomalies[:47]
test_easy = easy_anomalies[47:94]

gen_anomalies = gen_hard + gen_easy    # 50 total
test_anomalies = test_hard + test_easy  # 50 total

print(f"\nTrain normals:      {len(train_normals)}")
print(f"Canvas normals:     {len(canvas_normals)}")
print(f"Test normals:       {len(test_normals)}")
print(f"Gen anomalies:      {len(gen_anomalies)} (hard={len(gen_hard)}, easy={len(gen_easy)})")
print(f"Test anomalies:     {len(test_anomalies)} (hard={len(test_hard)}, easy={len(test_easy)})")


# ── Helpers ───────────────────────────────────────────────────────────────
def copy_images(file_list: list[Path], dest_dir: Path) -> None:
    dest_dir.mkdir(parents=True, exist_ok=True)
    for f in file_list:
        shutil.copy2(f, dest_dir / f.name)


def copy_masks_for_anomalies(anomaly_list: list[Path], dest_dir: Path) -> None:
    """Copy GT masks matching anomaly filenames (stem match, .png extension)."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    for f in anomaly_list:
        mask_path = MASK_DIR / f"{f.stem}.png"
        if mask_path.exists():
            shutil.copy2(mask_path, dest_dir / mask_path.name)
        else:
            print(f"  WARNING: no mask for {f.name}")


# Clean previous experiment
if EXPERIMENT.exists():
    shutil.rmtree(EXPERIMENT)

# ── Dataset Real ──────────────────────────────────────────────────────────
real = EXPERIMENT / "dataset_real"
copy_images(train_normals, real / "normal")
# Generation anomalies (the 50 whose masks we'll place on canvases)
copy_images(gen_hard, real / "anomaly" / "imgs" / "hard")
copy_images(gen_easy, real / "anomaly" / "imgs" / "easy")
copy_masks_for_anomalies(gen_hard, real / "anomaly" / "masks" / "hard")
copy_masks_for_anomalies(gen_easy, real / "anomaly" / "masks" / "easy")
# Test set
copy_images(test_normals, real / "test" / "normal")
copy_images(test_hard, real / "test" / "anomaly" / "hard")
copy_images(test_easy, real / "test" / "anomaly" / "easy")
copy_masks_for_anomalies(test_hard, real / "test" / "masks" / "hard")
copy_masks_for_anomalies(test_easy, real / "test" / "masks" / "easy")

# ── Dataset Synthetic ─────────────────────────────────────────────────────
synth = EXPERIMENT / "dataset_synthetic"
copy_images(train_normals, synth / "normal")

# Source materials for generation
copy_images(canvas_normals, synth / "source" / "canvas_normals" / "imgs")
# Reference anomalies (CLIP conditioning + masks for placement)
copy_images(gen_hard, synth / "source" / "reference_anomalies" / "hard" / "imgs")
copy_images(gen_easy, synth / "source" / "reference_anomalies" / "easy" / "imgs")
copy_masks_for_anomalies(gen_hard, synth / "source" / "reference_anomalies" / "hard" / "masks")
copy_masks_for_anomalies(gen_easy, synth / "source" / "reference_anomalies" / "easy" / "masks")

# Empty target dirs for generated images
(synth / "anomaly" / "imgs" / "hard").mkdir(parents=True, exist_ok=True)
(synth / "anomaly" / "imgs" / "easy").mkdir(parents=True, exist_ok=True)
(synth / "anomaly" / "masks" / "hard").mkdir(parents=True, exist_ok=True)
(synth / "anomaly" / "masks" / "easy").mkdir(parents=True, exist_ok=True)

# Test set (same test images as real — we compare detector performance)
copy_images(test_normals, synth / "test" / "normal")
copy_images(test_hard, synth / "test" / "anomaly" / "hard")
copy_images(test_easy, synth / "test" / "anomaly" / "easy")
copy_masks_for_anomalies(test_hard, synth / "test" / "masks" / "hard")
copy_masks_for_anomalies(test_easy, synth / "test" / "masks" / "easy")

# ── Save splits JSON ─────────────────────────────────────────────────────
splits = {
    "seed": SEED,
    "train_normals": [f.name for f in train_normals],
    "canvas_normals": [f.name for f in canvas_normals],
    "test_normals": [f.name for f in test_normals],
    "gen_anomalies_hard": [f.name for f in gen_hard],
    "gen_anomalies_easy": [f.name for f in gen_easy],
    "test_anomalies_hard": [f.name for f in test_hard],
    "test_anomalies_easy": [f.name for f in test_easy],
}
splits_path = EXPERIMENT / "splits.json"
with open(splits_path, "w") as f:
    json.dump(splits, f, indent=2)

# ── Summary ───────────────────────────────────────────────────────────────
print(f"\n{'='*60}")
print(f"Experiment prepared at: {EXPERIMENT}")
print(f"{'='*60}")
print(f"""
dataset_real/
  normal/                        {len(train_normals)} train normals
  anomaly/imgs/{{easy,hard}}       {len(gen_anomalies)} generation anomalies ({len(gen_hard)}h + {len(gen_easy)}e)
  anomaly/masks/{{easy,hard}}      {len(gen_anomalies)} GT masks
  test/normal/                   {len(test_normals)} test normals
  test/anomaly/{{easy,hard}}       {len(test_anomalies)} test anomalies ({len(test_hard)}h + {len(test_easy)}e)
  test/masks/{{easy,hard}}         {len(test_anomalies)} test GT masks

dataset_synthetic/
  normal/                        {len(train_normals)} train normals (same)
  source/canvas_normals/imgs/    {len(canvas_normals)} canvas normals
  source/reference_anomalies/    {len(gen_anomalies)} ref imgs + masks
  anomaly/imgs/{{easy,hard}}       EMPTY (to be generated)
  anomaly/masks/{{easy,hard}}      EMPTY (placed masks from viz script)
  test/                          same test set as dataset_real

splits.json saved for reproducibility (seed={SEED})
""")
